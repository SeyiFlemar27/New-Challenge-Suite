import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { initializeApp, deleteApp } from "firebase-admin/app";
import { getFirestore } from "firebase-admin/firestore";
import { dispatchNormalLifecycleJobs, recoverNormalLifecycleJobs, createNormalLifecycleScheduler, runNormalLifecycleJob } from "../lib/server/normal-lifecycle-scheduler.ts";
import { deliverNormalNotificationOutbox } from "../lib/server/normal-notifications.ts";
import { deliverNormalEmailOutbox } from "../lib/server/normal-email.ts";
assert.match(process.env.GCLOUD_PROJECT ?? "", /^demo-/);
assert.match(process.env.FIRESTORE_EMULATOR_HOST ?? "", /^(localhost|127\.0\.0\.1):\d+$/);
const app = initializeApp({ projectId: process.env.GCLOUD_PROJECT });
const db = getFirestore(app);
const id = `normal_scheduler_${randomUUID()}`;
const now = new Date("2026-10-14T12:00:00Z");
const job = db.collection("normalLifecycleJobs").doc(`normal_${id}`);
let count = 0;
const equal = (actual, expected, message) => { assert.equal(actual, expected, message); count++; };
try {
  equal(createNormalLifecycleScheduler({}), null, "unconfigured scheduler cannot call a provider");
  await job.set({ challengeId: id, version: 1, status: "pending", dispatchState: "pending", runAt: now.toISOString() });
  let calls = 0;
  const scheduler = { scheduleActivation: async input => { calls++; return { taskName: `${input.jobId}_${input.version}` }; } };
  await dispatchNormalLifecycleJobs(db, scheduler, now);
  await dispatchNormalLifecycleJobs(db, scheduler, now);
  equal(calls, 1, "already dispatched job is not dispatched twice");
  equal((await job.get()).data().taskName, `normal_${id}_1`, "provider task is tied to the persisted version");
  await recoverNormalLifecycleJobs(db, new Date(now.getTime() + 300_000));
  equal((await job.get()).data().version, 2, "missed delivery recovery increments job version");
  equal((await job.get()).data().dispatchState, "pending", "missed delivery returns to durable outbox");
  await job.update({ status: "running", leaseUntil: now.toISOString() });
  await recoverNormalLifecycleJobs(db, new Date(now.getTime() + 300_001));
  equal((await job.get()).data().status, "pending", "interrupted worker can recover after lease expiry");
  const event = db.collection("normalNotificationOutbox").doc(id);
  await event.set({ challengeId: id, creatorId: `${id}_creator`, type: "normal_voting_schedule", title: "Fixture voting", message: "Fixture full voting window", status: "pending", cursor: null });
  const batch = db.batch();
  for (let index = 0; index < 205; index++) batch.set(db.collection("challengeParticipants").doc(`${id}_${String(index).padStart(3, "0")}`), { challengeId: id, userId: `${id}_user_${index}`, status: "active" });
  await batch.commit();
  let delivered = 0;
  for (let page = 0; page < 3; page++) delivered += (await deliverNormalNotificationOutbox(db, id)).delivered;
  equal(delivered, 206, "bounded fanout reaches every participant and creator");
  equal((await event.get()).data().status, "completed", "fanout persists completion");
  equal((await deliverNormalNotificationOutbox(db, id)).delivered, 0, "retries do not duplicate completed notifications");
  const notices = await db.collection("notifications").where("targetId", "==", id).get();
  equal(notices.size, 206, "exactly one notification per recipient");
  equal(notices.docs.every(notice => notice.data().delivery.email === false), true, "unconfigured email is not reported delivered");
  equal((await deliverNormalEmailOutbox(db, id)).enabled, false, "email cannot activate without explicit configuration");
  let emailCalls = 0;
  const emailAdapter = { resolveRecipient: async () => "fixture@example.invalid", send: async message => { assert.ok(message.idempotencyKey.startsWith("normal-notice-")); emailCalls++; } };
  await deliverNormalEmailOutbox(db, id, emailAdapter);
  equal(emailCalls, 25, "email sends a bounded batch through the injected test adapter");
  await deliverNormalEmailOutbox(db, id, emailAdapter);
  equal(emailCalls, 50, "accepted rows do not starve later pending recipients");
  const emailRows = await db.collection("normalEmailOutbox").where("challengeId", "==", id).get();
  const acceptedRows = emailRows.docs.filter(row => row.data().status === "accepted");
  equal(acceptedRows.length, 50, "provider acceptance is recorded once per recipient");
  equal(acceptedRows.every(row => row.data().recipientDeliveryVerified === false), true, "acceptance is not claimed as delivered email");
  const retryRow = emailRows.docs.find(row => row.data().status === "pending");
  await retryRow.ref.update({ firstAttemptAt: new Date(Date.now() - 24 * 3600_000).toISOString() });
  await deliverNormalEmailOutbox(db, id, emailAdapter);
  equal((await retryRow.ref.get()).data().status, "review_required", "uncertain acceptance beyond provider deduplication retention cannot resend blindly");
  const expiry = new Date(now.getTime() + 20 * 60_000).toISOString();
  await db.collection("challenges").doc(id).set({ builderVersion: "normal_v3", normalLifecyclePolicyVersion: 1, status: "scheduled", registrationOpensAt: now.toISOString(), registrationDeadline: new Date(now.getTime() + 3600_000).toISOString(), submissionStartAt: new Date(now.getTime() + 3600_000).toISOString(), submissionDeadline: new Date(now.getTime() + 7200_000).toISOString() });
  await db.collection("challengeEntryPayments").doc(id).set({ challengeId: id, userId: `${id}_reserved`, status: "pending", reservationExpiresAt: expiry });
  await job.set({ challengeId: id, version: 3, status: "pending", dispatchState: "scheduled", runAt: now.toISOString() });
  await runNormalLifecycleJob(db, job.id, 3, now);
  equal((await job.get()).data().runAt, expiry, "next durable wake-up includes the 20-minute reservation expiration");
  await runNormalLifecycleJob(db, job.id, 4, new Date(expiry));
  equal((await db.collection("challengeEntryPayments").doc(id).get()).data().status, "expired", "scheduled expiry persists without initiating provider operations");
  console.log(`Normal scheduler and notification emulator: ${count} assertions passed.`);
} finally {
  await job.delete();
  await db.collection("challenges").doc(id).delete();
  await db.collection("challengeEntryPayments").doc(id).delete();
  for (const [collection, field] of [["challengeParticipants", "challengeId"], ["normalNotificationOutbox", "challengeId"], ["normalEmailOutbox", "challengeId"], ["notifications", "targetId"]]) {
    const docs = await db.collection(collection).where(field, "==", id).get();
    await Promise.all(docs.docs.map(document => document.ref.delete()));
  }
  await deleteApp(app);
}
