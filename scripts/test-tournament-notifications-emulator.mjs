import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { initializeApp } from "firebase-admin/app";
import { getFirestore } from "firebase-admin/firestore";
import { deliverTournamentNotifications } from "../lib/server/tournament-notifications.ts";
import { deliverTournamentEmailOutbox } from "../lib/server/normal-email.ts";
assert.match(process.env.GCLOUD_PROJECT ?? "", /^demo-/);
assert.match(process.env.FIRESTORE_EMULATOR_HOST ?? "", /^127\.0\.0\.1:\d+$/);
const db = getFirestore(initializeApp({ projectId: process.env.GCLOUD_PROJECT }));
const id = `notices_${randomUUID()}`, host = `${id}_host`, first = `${id}_first`, second = `${id}_second`;
let assertions = 0;
const equal = (actual, expected) => { assert.equal(actual, expected); assertions++; };
try {
  await db.collection("tournaments").doc(id).set({ hostId: host });
  for (const uid of [first, second]) await db.collection("tournamentParticipants").doc(uid).set({ tournamentId: id, userId: uid, status: "active" });
  await db.collection("tournamentTeams").doc(`${id}_forming`).set({ tournamentId: id, status: "forming", memberUserIds: [`${id}_not_registered`] });
  await db.collection("tournamentParticipants").doc(`${id}_withdrawn`).set({ tournamentId: id, status: "withdrawn", userId: `${id}_withdrawn_user` });
  await db.collection("notificationPreferences").doc(second).set({ inApp: false });
  const event = db.collection("tournamentAuditEvents").doc(`${id}_activation`);
  await event.set({ tournamentId: id, action: "full_tournament_activated", actorId: "system_tournament_activation", createdAt: "2026-10-10T12:00:00.000Z" });
  equal((await deliverTournamentNotifications(db, id)).delivered, 2);
  const firstNotice = await db.collection("notifications").where("userId", "==", first).get();
  equal(firstNotice.size, 1); equal(firstNotice.docs[0].data().actionUrl, `/tournaments/${id}`);
  await firstNotice.docs[0].ref.update({ read: true, status: "read" });
  const retries = await Promise.all([deliverTournamentNotifications(db, id), deliverTournamentNotifications(db, id)]);
  equal(retries.reduce((sum, row) => sum + row.delivered, 0), 0);
  equal((await firstNotice.docs[0].ref.get()).data().read, true);
  equal((await db.collection("notifications").where("userId", "==", `${id}_not_registered`).get()).size, 0);
  equal((await event.get()).data().notificationDeliveredAt, undefined);
  equal((await db.collection("tournamentNotificationDeliveries").doc(event.id).get()).data().status, "completed");
  equal((await firstNotice.docs[0].ref.get()).data().delivery.email, false);
  const matchId = `${id}_match`;
  await db.collection("tournamentMatches").doc(matchId).set({ tournamentId: id, participantAId: first, participantBId: second });
  await db.collection("tournamentAuditEvents").doc(`${id}_voting`).set({ tournamentId: id, action: "match_voting_opened", actorId: "system_tournament_lifecycle", metadata: { matchId } });
  equal((await deliverTournamentNotifications(db, id)).delivered, 2);
  const next = await db.collection("notifications").where("userId", "==", first).get();
  equal(next.size, 2); equal(next.docs.some(doc => doc.data().actionUrl.endsWith(`/matches/${matchId}`)), true);
  equal((await db.collection("notifications").where("userId", "==", second).get()).size, 0);
  for (const action of ["participant_registered", "submitted_for_review", "tournament_approve", "tournament_reject", "team_slot_reserved", "match_assigned", "submission_submitted", "submission_replaced", "submission_approved", "submission_rejected", "no_submission_extension", "match_voting_closed", "competitor_advanced", "competitor_eliminated", "double_forfeit_dependency_hold", "submission_forfeit", "tournament_settlement_prepared", "team_entitlements_reconciled", "pause", "resume"]) {
    await db.collection("tournamentAuditEvents").doc(`${id}_${action}`).set({ tournamentId: id, action, actorId: first, metadata: { matchId, targetCompetitorIds: [first], rosterUserIds: [first] } });
    equal((await deliverTournamentNotifications(db, id)).delivered, 2);
    equal((await deliverTournamentNotifications(db, id)).delivered, 0);
  }
  equal((await db.collection("notifications").where("userId", "==", `${id}_withdrawn_user`).get()).size, 0);
  const records = await db.collection("notifications").where("userId", "==", first).get();
  equal(records.docs.every(row => row.data().delivery.email === false && row.data().delivery.push === false), true);
  equal((await firstNotice.docs[0].ref.get()).data().read, true);
  await db.collection("notificationPreferences").doc(first).set({ email: true }, { merge: true });
  await db.collection("tournamentAuditEvents").doc(`${id}_email_permission`).set({ tournamentId: id, action: "resume", actorId: first, metadata: { matchId } });
  equal((await deliverTournamentNotifications(db, id)).delivered, 2);
  const outbox = await db.collection("tournamentEmailOutbox").where("tournamentId", "==", id).get();
  equal(outbox.size, 1);
  equal((await deliverTournamentEmailOutbox(db, id)).enabled, false);
  const sent = [];
  const adapter = { resolveRecipient: async () => "isolated-recipient@example.test", send: async message => { sent.push(message.idempotencyKey); } };
  const dispatches = await Promise.all([deliverTournamentEmailOutbox(db, id, adapter), deliverTournamentEmailOutbox(db, id, adapter)]);
  equal(dispatches.reduce((sum, row) => sum + row.accepted, 0), 1);
  equal(sent.length, 1);
  equal((await outbox.docs[0].ref.get()).data().status, "accepted");
  equal((await outbox.docs[0].ref.get()).data().recipientDeliveryVerified, false);
  equal((await deliverTournamentEmailOutbox(db, id, adapter)).accepted, 0);
  await db.collection("notificationPreferences").doc(second).set({ inApp: true });
  await db.collection("tournamentAuditEvents").doc(`${id}_target_without_match`).set({ tournamentId: id, action: "competitor_advanced", actorId: "system_tournament_lifecycle", metadata: { targetCompetitorIds: [first] } });
  equal((await deliverTournamentNotifications(db, id)).delivered, 2);
  equal((await db.collection("notifications").where("userId", "==", second).get()).size, 0);
  console.log(`Tournament notifications: ${assertions} Firestore assertions passed; no email provider activated.`);
} finally { await db.terminate(); }
