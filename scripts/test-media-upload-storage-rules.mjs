import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { deleteApp, initializeApp } from "firebase/app";
import { connectAuthEmulator, createUserWithEmailAndPassword, getAuth, signInWithEmailAndPassword } from "firebase/auth";
import { connectStorageEmulator, getBytes, getStorage, ref, uploadBytes } from "firebase/storage";

const projectId = process.env.CHALLENGE_SUITE_E2E_PROJECT_ID ?? process.env.GCLOUD_PROJECT ?? process.env.FIREBASE_PROJECT_ID ?? "demo-challenge-suite";
assert.ok(projectId.startsWith("demo-"), "Storage Rules tests require an isolated demo-* Firebase project ID.");
const authEmulator = process.env.FIREBASE_AUTH_EMULATOR_HOST ?? "127.0.0.1:9099";
const firestoreEmulator = process.env.FIRESTORE_EMULATOR_HOST ?? "127.0.0.1:8080";
const storageEmulator = process.env.FIREBASE_STORAGE_EMULATOR_HOST ?? "127.0.0.1:9199";
const firestoreBase = `http://${firestoreEmulator}/v1/projects/${projectId}/databases/(default)/documents`;
const app = initializeApp({ apiKey: "fake-api-key", authDomain: `${projectId}.firebaseapp.com`, projectId, storageBucket: `${projectId}.appspot.com` }, `media-rules-${randomUUID()}`);
const auth = getAuth(app);
connectAuthEmulator(auth, `http://${authEmulator}`, { disableWarnings: true });
const storage = getStorage(app);
const storageUrl = new URL(`http://${storageEmulator}`);
connectStorageEmulator(storage, storageUrl.hostname, Number(storageUrl.port || 80));
const assertions = [];

function string(value) { return { stringValue: value }; }
function bool(value) { return { booleanValue: value }; }
function array(values) { return { arrayValue: { values: values.map(string) } }; }

async function user(label) {
  const email = `${label}-${randomUUID()}@example.test`;
  const password = "TestPassword123!";
  const credential = await createUserWithEmailAndPassword(auth, email, password);
  return { uid: credential.user.uid, email, password };
}

async function signIn(account) {
  await signInWithEmailAndPassword(auth, account.email, account.password);
}

async function putDocument(collection, id, fields) {
  const response = await fetch(`${firestoreBase}/${collection}/${id}`, {
    method: "PATCH",
    headers: { authorization: "Bearer owner", "content-type": "application/json" },
    body: JSON.stringify({ fields }),
  });
  assert.equal(response.ok, true, `Firestore emulator fixture write failed for ${collection}/${id}: ${response.status} ${await response.text()}`);
}

async function upload(account, path, contentType, allowed, label) {
  await signIn(account);
  try {
    await uploadBytes(ref(storage, path), new Blob([`upload-fixture-${randomUUID()}`], { type: contentType }), { contentType });
    assertions.push(`${label}: allowed`);
    assert.equal(allowed, true, `${label} should be allowed`);
    return true;
  } catch (error) {
    assertions.push(`${label}: denied (${error?.code ?? "storage-error"})`);
    assert.equal(allowed, false, `${label} should be allowed but Storage rejected it (${error?.code ?? "storage-error"})`);
    return false;
  }
}

async function canRead(account, path, allowed, label) {
  await signIn(account);
  try {
    await getBytes(ref(storage, path));
    assertions.push(`${label}: readable`);
    assert.equal(allowed, true, `${label} should be denied`);
  } catch (error) {
    assertions.push(`${label}: read denied (${error?.code ?? "storage-error"})`);
    assert.equal(allowed, false, `${label} should be readable but Storage rejected it (${error?.code ?? "storage-error"})`);
  }
}

const owner = await user("creator");
const sponsor = await user("sponsor");
const recipient = await user("recipient");
const admin = await user("admin");
const outsider = await user("outsider");

// Challenge builder folders preserve their type and owner constraints.
await upload(owner, `challenges/drafts/${owner.uid}/banner/${randomUUID()}.png`, "image/png", true, "challenge banner upload");
await upload(owner, `challenges/drafts/${owner.uid}/gallery/${randomUUID()}.png`, "image/png", true, "challenge gallery upload");
await upload(owner, `challenges/drafts/${owner.uid}/video/${randomUUID()}.mp4`, "video/mp4", true, "challenge video upload");
await upload(owner, `challenges/drafts/${owner.uid}/documents/${randomUUID()}.pdf`, "application/pdf", true, "challenge document upload");
await upload(outsider, `challenges/drafts/${owner.uid}/banner/${randomUUID()}.png`, "image/png", false, "foreign challenge draft denied");
await upload(owner, `challenges/drafts/${owner.uid}/documents/${randomUUID()}.png`, "image/png", false, "wrong challenge document MIME denied");

// Participant submissions use the same folder-bearing path generated by submissionMediaPath.
const challengeId = `challenge-${randomUUID()}`;
await upload(owner, `challenges/${challengeId}/submissions/${owner.uid}/images/${randomUUID()}.png`, "image/png", true, "participant image submission upload");
await upload(owner, `challenges/${challengeId}/submissions/${owner.uid}/videos/${randomUUID()}.avi`, "video/x-msvideo", true, "participant AVI submission upload");
await upload(owner, `challenges/${challengeId}/submissions/${owner.uid}/documents/${randomUUID()}.pdf`, "application/pdf", true, "participant document submission upload");
await upload(outsider, `challenges/${challengeId}/submissions/${owner.uid}/images/${randomUUID()}.png`, "image/png", false, "foreign participant submission denied");
await upload(owner, `challenges/${challengeId}/submissions/${owner.uid}/${randomUUID()}.png`, "image/png", false, "legacy folderless submission path denied");
await upload(owner, `challenges/${challengeId}/submissions/${owner.uid}/documents/${randomUUID()}.png`, "image/png", false, "wrong submission document MIME denied");

// Public profile and Sponsor assets retain owned writes; only profile media is public-readable.
const profilePath = `users/${owner.uid}/profile/avatar/${randomUUID()}.png`;
await upload(owner, profilePath, "image/png", true, "profile avatar upload");
await canRead(outsider, profilePath, true, "public profile image");
await upload(outsider, `users/${owner.uid}/profile/avatar/${randomUUID()}.png`, "image/png", false, "foreign profile image denied");
const sponsorLogo = `sponsors/${sponsor.uid}/logo/${randomUUID()}.png`;
await upload(sponsor, sponsorLogo, "image/png", true, "Sponsor logo upload");
await upload(sponsor, `sponsors/${sponsor.uid}/banner/${randomUUID()}.png`, "image/png", true, "Sponsor banner upload");
await upload(outsider, `sponsors/${sponsor.uid}/logo/${randomUUID()}.png`, "image/png", false, "foreign Sponsor asset denied");
await upload(sponsor, `sponsors/${sponsor.uid}/creative/${randomUUID()}.png`, "image/png", false, "unconfigured Sponsor asset folder denied");

// Conversation attachments are readable only by participants and are writable only by the Sponsor.
const conversationId = `conversation-${randomUUID()}`;
await putDocument("sponsorConversations", conversationId, { sponsorId: string(sponsor.uid), recipientId: string(recipient.uid), status: string("active") });
const conversationImage = `sponsor-conversations/${conversationId}/${sponsor.uid}/images/${randomUUID()}.png`;
const conversationPdf = `sponsor-conversations/${conversationId}/${sponsor.uid}/documents/${randomUUID()}.pdf`;
await upload(sponsor, conversationImage, "image/png", true, "Sponsor conversation image attachment");
await upload(sponsor, conversationPdf, "application/pdf", true, "Sponsor conversation PDF attachment");
await canRead(recipient, conversationImage, true, "conversation recipient can read attachment");
await canRead(outsider, conversationImage, false, "unrelated user cannot read conversation attachment");
await upload(recipient, `sponsor-conversations/${conversationId}/${recipient.uid}/images/${randomUUID()}.png`, "image/png", false, "conversation recipient cannot upload as Sponsor");

// Tournament draft media and match submissions are authenticated by owner/participant records.
await upload(owner, `tournaments/drafts/${owner.uid}/cover/${randomUUID()}.png`, "image/png", true, "Tournament draft cover upload");
await upload(owner, `tournaments/drafts/${owner.uid}/trailer/${randomUUID()}.mp4`, "video/mp4", true, "Tournament draft trailer upload");
await upload(owner, `tournaments/drafts/${owner.uid}/cover/${randomUUID()}.mp4`, "video/mp4", false, "wrong Tournament cover MIME denied");
await upload(outsider, `tournaments/drafts/${owner.uid}/cover/${randomUUID()}.png`, "image/png", false, "foreign Tournament draft denied");
const tournamentId = `tournament-${randomUUID()}`;
const roundId = `${tournamentId}_round_1`;
const matchId = `${tournamentId}_r1_m1`;
const participantId = `${tournamentId}_${owner.uid}`;
await putDocument("tournamentParticipants", participantId, { tournamentId: string(tournamentId), userId: string(owner.uid), status: string("registered") });
await upload(owner, `tournaments/${tournamentId}/rounds/${roundId}/matches/${matchId}/participants/${participantId}/images/${randomUUID()}.png`, "image/png", true, "registered Tournament participant submission upload");
await upload(outsider, `tournaments/${tournamentId}/rounds/${roundId}/matches/${matchId}/participants/${participantId}/images/${randomUUID()}.png`, "image/png", false, "nonparticipant Tournament submission denied");
const teamId = `team-${randomUUID()}`;
await putDocument("tournamentTeamMemberships", `${tournamentId}_${sponsor.uid}`, { tournamentId: string(tournamentId), userId: string(sponsor.uid), teamId: string(teamId), role: string("captain"), status: string("active") });
await upload(sponsor, `tournaments/${tournamentId}/rounds/${roundId}/matches/${matchId}/participants/${teamId}/videos/${randomUUID()}.mp4`, "video/mp4", true, "active Tournament captain team submission upload");
await putDocument("tournamentTeamMemberships", `${tournamentId}_${recipient.uid}`, { tournamentId: string(tournamentId), userId: string(recipient.uid), teamId: string(teamId), role: string("member"), status: string("active") });
await upload(recipient, `tournaments/${tournamentId}/rounds/${roundId}/matches/${matchId}/participants/${teamId}/images/${randomUUID()}.png`, "image/png", false, "noncaptain team member Tournament submission denied");

// Admin upload authorization follows the active profile state, not arbitrary client metadata.
await putDocument("users", admin.uid, {
  isAdmin: bool(true), adminRole: string("admin"), adminRoles: array(["admin"]),
  adminAccessStatus: string("active"), adminSecuritySetupComplete: bool(true),
});
const publicContentPoster = `admin/public-content/hero-poster/${randomUUID()}.png`;
const publicContentVideo = `admin/public-content/hero-video/${randomUUID()}.mp4`;
await upload(admin, publicContentPoster, "image/png", true, "authorized Admin public-content poster upload");
await upload(admin, publicContentVideo, "video/mp4", true, "authorized Admin public-content video upload");
await upload(outsider, `admin/public-content/hero-poster/${randomUUID()}.png`, "image/png", false, "non-Admin public-content upload denied");
await putDocument("users", admin.uid, { adminAccessStatus: string("suspended") });
await upload(admin, `admin/public-content/hero-poster/${randomUUID()}.png`, "image/png", false, "suspended Admin public-content upload denied");

console.log(`PASS Firebase Storage Emulator media namespace suite: ${assertions.length} upload/read assertions`);
await deleteApp(app);
