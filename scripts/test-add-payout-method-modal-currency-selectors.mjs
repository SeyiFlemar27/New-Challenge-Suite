import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const page = readFileSync("app/earnings/page.tsx", "utf8");
const api = readFileSync("app/api/payout-methods/route.ts", "utf8");
for (const name of ["Payoneer account", "Bank transfer", "PayPal account"]) assert.match(page, new RegExp(name));
assert.match(page, /Up to 1 business day/);
assert.match(page, /Up to 3 business days/);
assert.match(page, /Fees may apply/);
assert.match(page, /USD/);
assert.match(page, /disabled=\{!selected\}/);
assert.match(page, /document\.addEventListener\("keydown"/);
assert.match(page, /event\.key === "Escape"/);
for (const field of ["Account holder name", "Bank name", "Account number", "Bank code", "Routing information", "Country", "Currency", "Account type"]) assert.match(page, new RegExp(field));
assert.match(api, /provider_connection_required/);
assert.match(api, /providerConnected: false/);
assert.match(api, /transferEnabled: false/);
assert.match(api, /accountNumber\.slice\(-4\)/);
assert.doesNotMatch(api, /email\s*=|payout account email/);
assert.match(page, /Payout Method Added/);
assert.match(page, /Set as Primary/);
console.log("payout setup contract passed");