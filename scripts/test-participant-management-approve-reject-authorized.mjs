import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const page = readFileSync("app/host/[tool]/page.tsx", "utf8");
const api = readFileSync("app/api/challenges/[id]/manage/route.ts", "utf8");
const operations = readFileSync("app/api/host/operations/route.ts", "utf8");
assert.match(page, /Select a competition to manage participants/);
assert.match(page, /Choose one of your hosted competitions/);
for (const label of ["All", "Pending", "Approved", "Rejected", "Checked In", "Disqualified"]) assert.match(page, new RegExp(label));
for (const label of ["Not Required", "Confirmed", "Refunded", "Resubmission Requested"]) assert.match(page, new RegExp(label));
assert.match(page, /Search participant/);
assert.match(page, /Message Participant/);
assert.match(page, /Export Participants/);
assert.match(operations, /creatorId/);
assert.match(operations, /hostId/);
assert.match(api, /Check-in is available only for Live Events/);
assert.match(api, /pending_admin_review/);
assert.match(api, /request_disqualification/);
assert.match(api, /writeAuditLog/);
assert.doesNotMatch(page, /Operational changes are disabled/i);
console.log("participant management contract passed");